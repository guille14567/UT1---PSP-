        public void rellenarCampos( String asunto,int dia,int mes,int año,String cantidad, String tipo) {

        asuntoCampo.setText(asunto);
        diaCampo.setValue(dia);
        mesCampo.setValue(mes);
        añoCampo.setValue(año);
        cantidadCampo.setText(cantidad);
        tipoComboBox.setSelectedItem(tipo);
    }

    public void limpiarCampos() {
        asuntoCampo.setText("");
        cantidadCampo.setText("");

        diaCampo.setValue(1);
        mesCampo.setValue(1);
        añoCampo.setValue(2000);

        tipoComboBox.setSelectedIndex(0);
    }
    
     public void mostrarError(String error) {
        mensajeError.setText(error);
    }

    public void limpiarError() {
        mensajeError.setText("");
    }
      public void añadirFacturaLista(Factura factura) {
        modeloLista.addElement(textoFactura(factura));
    }

    public void actualizarFacturaLista(
            int posicion, Factura factura) {

        modeloLista.set(posicion, textoFactura(factura));
    }

    public void eliminarFacturaLista(int posicion) {
        modeloLista.remove(posicion);
    }

    private String textoFactura(Factura factura) {
        return factura.getAsunto() + ":"
                + factura.getFecha() + ":"
                + factura.getCantidad() + ":"
                + factura.getTipo();
    }
